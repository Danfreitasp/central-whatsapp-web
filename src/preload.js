const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('centralWhatsApp', {
  listProfiles: () => ipcRenderer.invoke('profiles:list'),
  searchAllConversations: (input) => ipcRenderer.invoke('global-search:run', input),
  cancelGlobalSearch: () => ipcRenderer.invoke('global-search:cancel'),
  openGlobalSearchResult: (result) => ipcRenderer.invoke('global-search:open', result),
  getGlobalSearchIndexStatus: () => ipcRenderer.invoke('global-search:index-status'),
  rebuildGlobalSearchIndex: () => ipcRenderer.invoke('global-search:rebuild-index'),
  clearGlobalSearchIndex: () => ipcRenderer.invoke('global-search:clear-index'),
  backupConversation: (profileId) => ipcRenderer.invoke('conversation-backup:create', profileId),
  cancelConversationBackup: (profileId) => ipcRenderer.invoke('conversation-backup:cancel', profileId),
  listTemplates: () => ipcRenderer.invoke('templates:list'),
  addTemplate: (input) => ipcRenderer.invoke('templates:add', input),
  updateTemplate: (input) => ipcRenderer.invoke('templates:update', input),
  removeTemplate: (id) => ipcRenderer.invoke('templates:remove', id),
  listLabels: () => ipcRenderer.invoke('labels:list'),
  addLabel: (input) => ipcRenderer.invoke('labels:add', input),
  removeLabel: (id) => ipcRenderer.invoke('labels:remove', id),
  getCurrentChatLabels: () => ipcRenderer.invoke('labels:current-chat'),
  toggleChatLabel: (input) => ipcRenderer.invoke('labels:toggle-chat', input),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  getDispatchState: (profileId) => ipcRenderer.invoke('dispatch:state', profileId),
  getDispatchStates: () => ipcRenderer.invoke('dispatch:states'),
  startDispatch: (input) => ipcRenderer.invoke('dispatch:start', input),
  listDistributions: () => ipcRenderer.invoke('dispatch:distributions:list'),
  startDistribution: (input) => ipcRenderer.invoke('dispatch:distribution:start', input),
  stopDistribution: (id) => ipcRenderer.invoke('dispatch:distribution:stop', id),
  toggleDistributionPause: (id) => ipcRenderer.invoke('dispatch:distribution:toggle-pause', id),
  stopDispatch: (profileId) => ipcRenderer.invoke('dispatch:stop', profileId),
  toggleDispatchPause: (profileId) => ipcRenderer.invoke('dispatch:toggle-pause', profileId),
  listScheduledDispatches: () => ipcRenderer.invoke('dispatch:schedules:list'),
  scheduleDispatch: (input) => ipcRenderer.invoke('dispatch:schedule', input),
  cancelScheduledDispatch: (id) => ipcRenderer.invoke('dispatch:schedule:cancel', id),
  saveDispatchFailures: (failures) => ipcRenderer.invoke('dispatch:failures:save', failures),
  listDispatchHistory: (filters) => ipcRenderer.invoke('dispatch:history:list', filters),
  saveDispatchHistory: (filters) => ipcRenderer.invoke('dispatch:history:save', filters),
  listCampaigns: () => ipcRenderer.invoke('campaigns:list'),
  createCampaign: (input) => ipcRenderer.invoke('campaigns:create', input),
  getCampaignContacts: (input) => ipcRenderer.invoke('campaigns:contacts', input),
  releaseCampaignSkipped: (campaignId) => ipcRenderer.invoke('campaigns:release-skipped', campaignId),
  removeCampaign: (campaignId) => ipcRenderer.invoke('campaigns:remove', campaignId),
  exportCampaign: (campaignId) => ipcRenderer.invoke('campaigns:export', campaignId),
  beginAdd: () => ipcRenderer.invoke('profiles:begin-add'),
  cancelAdd: () => ipcRenderer.invoke('profiles:cancel-add'),
  insertText: (text) => ipcRenderer.invoke('profiles:insert-text', text),
  addProfile: (input) => ipcRenderer.invoke('profiles:add', input),
  selectProfile: (id) => ipcRenderer.invoke('profiles:select', id),
  setZoom: (input) => ipcRenderer.invoke('profiles:set-zoom', input),
  renameProfile: (input) => ipcRenderer.invoke('profiles:rename', input),
  reorderProfiles: (input) => ipcRenderer.invoke('profiles:reorder', input),
  removeProfile: (id) => ipcRenderer.invoke('profiles:remove', id),
  onUnreadChanged: (callback) => ipcRenderer.on('profiles:unread-changed', (_event, data) => callback(data)),
  onProfileActivated: (callback) => ipcRenderer.on('profiles:activated', (_event, data) => callback(data)),
  onGlobalSearchProgress: (callback) => ipcRenderer.on('global-search:progress', (_event, data) => callback(data)),
  onDispatchProgress: (callback) => ipcRenderer.on('dispatch:progress', (_event, data) => callback(data)),
  onDispatchStateChanged: (callback) => ipcRenderer.on('dispatch:state-changed', (_event, data) => callback(data)),
  onScheduledDispatchesChanged: (callback) => ipcRenderer.on('dispatch:schedules-changed', (_event, data) => callback(data)),
  onScheduledDispatchTriggered: (callback) => ipcRenderer.on('dispatch:schedule-triggered', (_event, data) => callback(data)),
  onDispatchDone: (callback) => ipcRenderer.on('dispatch:done', (_event, data) => callback(data)),
  onDistributionStateChanged: (callback) => ipcRenderer.on('dispatch:distribution-state-changed', (_event, data) => callback(data)),
  onDistributionDone: (callback) => ipcRenderer.on('dispatch:distribution-done', (_event, data) => callback(data)),
  onDispatchHistoryChanged: (callback) => ipcRenderer.on('dispatch:history-changed', (_event, data) => callback(data)),
  onCampaignsChanged: (callback) => ipcRenderer.on('campaigns:changed', (_event, data) => callback(data)),
  onConversationBackupProgress: (callback) => ipcRenderer.on('conversation-backup:progress', (_event, data) => callback(data))
});
